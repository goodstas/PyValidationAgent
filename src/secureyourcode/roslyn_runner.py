"""Roslyn stage: scratch build of the frozen snapshot, SARIF 2.1.0 parsing and normalisation."""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import time
from dataclasses import dataclass, field
from pathlib import Path
from urllib.parse import unquote, urlparse

from .schemas import CATEGORY_BY_RULE, RoslynCandidate
from .workspace import read_lines

SECURITY_RULE_IDS: tuple[str, ...] = ("CA3001", "CA3003", "CA3006", "CA5350", "CA5394")
PERF_RULE_IDS: tuple[str, ...] = ("PERF001", "PERF003", "PERF004")
SELECTED_RULE_IDS: tuple[str, ...] = SECURITY_RULE_IDS + PERF_RULE_IDS

# Known model/provider secrets stripped from every analyzer / Graphify child process (hygiene, not a sandbox).
SECRET_ENV_KEYS = {
    "GRAPHIFY_OUT",
    "GOOGLE_APPLICATION_CREDENTIALS",
    "GEMINI_API_KEY",
    "GOOGLE_API_KEY",
    "OPENAI_API_KEY",
    "ANTHROPIC_API_KEY",
    "KIMI_API_KEY",
    "MOONSHOT_API_KEY",
    "DEEPSEEK_API_KEY",
    "SERVICE_TOKEN",
    "GRAPHIFY_API_KEY",
}


def child_env(extra: dict[str, str] | None = None) -> dict[str, str]:
    env = {k: v for k, v in os.environ.items() if k not in SECRET_ENV_KEYS and not k.endswith("_API_KEY")}
    env.update(extra or {})
    return env


def candidate_id(rule_id: str, file: str, start_line: int, end_line: int) -> str:
    return hashlib.sha256(f"{rule_id}|{file}|{start_line}|{end_line}".encode("utf-8")).hexdigest()[:12]


@dataclass
class RoslynResult:
    status: str  # ok | failed
    candidates: list[RoslynCandidate] = field(default_factory=list)
    emitted_rule_ids: list[str] = field(default_factory=list)
    missing_rule_ids: list[str] = field(default_factory=list)
    error: str | None = None
    build_exit_code: int | None = None
    sarif_version: str | None = None
    log_tail: str = ""
    dropped_locations: list[str] = field(default_factory=list)


def prepare_build_dir(build_dir: Path, analyzer_dll: Path, global_json: Path, sarif_path: Path) -> None:
    """Generate isolating MSBuild/analyzer config only inside the disposable scratch copy."""
    severities = "\n".join(f"dotnet_diagnostic.{rid}.severity = warning" for rid in SELECTED_RULE_IDS)
    (build_dir / ".editorconfig").write_text(f"root = true\n\n[*.cs]\n{severities}\n", encoding="utf-8")
    shutil.copyfile(global_json, build_dir / "global.json")
    (build_dir / "Directory.Build.props").write_text(
        f"""<Project>
  <!-- Generated by SecureYourCode in the scratch build root; stops MSBuild from importing parent props. -->
  <PropertyGroup>
    <EnableNETAnalyzers>true</EnableNETAnalyzers>
    <RunAnalyzersDuringBuild>true</RunAnalyzersDuringBuild>
    <TreatWarningsAsErrors>false</TreatWarningsAsErrors>
    <ErrorLog>{sarif_path.as_posix()},version=2.1</ErrorLog>
    <UseSharedCompilation>false</UseSharedCompilation>
    <GenerateDocumentationFile>false</GenerateDocumentationFile>
  </PropertyGroup>
</Project>
""",
        encoding="utf-8",
    )
    (build_dir / "Directory.Build.targets").write_text(
        f"""<Project>
  <ItemGroup>
    <Analyzer Include="{analyzer_dll.as_posix()}" />
  </ItemGroup>
</Project>
""",
        encoding="utf-8",
    )


def _run(cmd: list[str], cwd: Path, timeout: float) -> subprocess.CompletedProcess[str]:
    env = child_env({"DOTNET_CLI_TELEMETRY_OPTOUT": "1", "DOTNET_NOLOGO": "1", "DOTNET_SKIP_FIRST_TIME_EXPERIENCE": "1", "MSBUILDDISABLENODEREUSE": "1"})
    return subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True, timeout=max(timeout, 1), check=False)


def run_roslyn(staged_root: Path, build_dir: Path, analyzer_dll: Path, global_json: Path, timeout: float) -> RoslynResult:
    if not analyzer_dll.is_file():
        return RoslynResult(status="failed", error=f"Performance analyzer DLL not found at {analyzer_dll}; build it first (see README).")
    sarif_path = build_dir.parent / f"{build_dir.name}.sarif"
    if sarif_path.exists():
        sarif_path.unlink()
    prepare_build_dir(build_dir, analyzer_dll, global_json, sarif_path)
    projects = sorted(build_dir.rglob("*.csproj"))
    if len(projects) != 1:
        return RoslynResult(status="failed", error=f"Expected one project in scratch build, found {len(projects)}")
    project = projects[0]
    deadline = time.monotonic() + timeout
    try:
        restore = _run(["dotnet", "restore", str(project), "-nodeReuse:false"], build_dir, deadline - time.monotonic())
        if restore.returncode != 0:
            return RoslynResult(status="failed", error="dotnet restore failed", build_exit_code=restore.returncode, log_tail=_tail(restore))
        build = _run(
            ["dotnet", "build", str(project), "-t:Rebuild", "--no-restore", "-nodeReuse:false", "-c", "Debug", "-v:minimal"],
            build_dir,
            deadline - time.monotonic(),
        )
    except subprocess.TimeoutExpired:
        return RoslynResult(status="failed", error="dotnet restore/build timed out")
    except FileNotFoundError:
        return RoslynResult(status="failed", error="dotnet executable not found on PATH")
    if build.returncode != 0:
        return RoslynResult(status="failed", error="dotnet build failed", build_exit_code=build.returncode, log_tail=_tail(build))
    if not sarif_path.is_file():
        return RoslynResult(status="failed", error="Compiler SARIF (ErrorLog) was not produced", build_exit_code=0, log_tail=_tail(build))
    result = parse_sarif(sarif_path, build_dir, staged_root)
    result.build_exit_code = 0
    result.log_tail = _tail(build)
    return result


def _tail(proc: subprocess.CompletedProcess[str], limit: int = 4000) -> str:
    return ((proc.stdout or "") + (proc.stderr or ""))[-limit:]


def normalize_uri(uri: str, base_uris: dict[str, str], uri_base_id: str | None, build_dir: Path) -> Path | None:
    """Turn a SARIF artifact URI (file://, percent-encoded, relative, Windows separators) into an absolute path."""
    uri = uri.strip()
    if uri_base_id and uri_base_id in base_uris:
        base = base_uris[uri_base_id]
        uri = base.rstrip("/") + "/" + uri.lstrip("/")
    if uri.lower().startswith("file:"):
        parsed = urlparse(uri)
        path = unquote(parsed.path)
        if parsed.netloc and parsed.netloc.lower() != "localhost":
            path = f"//{parsed.netloc}{path}"
        if len(path) >= 3 and path[0] == "/" and path[2] == ":":  # /C:/x -> C:/x
            path = path[1:]
        return Path(path.replace("\\", "/"))
    path = unquote(uri).replace("\\", "/")
    p = Path(path)
    return p if p.is_absolute() else build_dir / p


def parse_sarif(sarif_path: Path, build_dir: Path, staged_root: Path, selected: tuple[str, ...] = SELECTED_RULE_IDS) -> RoslynResult:
    try:
        sarif = json.loads(sarif_path.read_text(encoding="utf-8-sig"))
    except (OSError, json.JSONDecodeError) as exc:
        return RoslynResult(status="failed", error=f"Unreadable SARIF: {exc}")
    version = sarif.get("version")
    if version != "2.1.0" or not isinstance(sarif.get("runs"), list):
        return RoslynResult(status="failed", error=f"Expected SARIF 2.1.0, found {version!r}", sarif_version=version)
    build_root = build_dir.resolve()
    staged_root = staged_root.resolve()
    seen: dict[str, RoslynCandidate] = {}
    dropped: list[str] = []
    for run in sarif["runs"]:
        base_uris = {k: v.get("uri", "") for k, v in (run.get("originalUriBaseIds") or {}).items()}
        for res in run.get("results") or []:
            rule_id = res.get("ruleId")
            if rule_id not in selected:
                continue
            locs = res.get("locations") or []
            if not locs:
                dropped.append(f"{rule_id}: no location")
                continue
            phys = locs[0].get("physicalLocation") or {}
            art = phys.get("artifactLocation") or {}
            region = phys.get("region") or {}
            abs_path = normalize_uri(art.get("uri", ""), base_uris, art.get("uriBaseId"), build_root)
            if abs_path is None:
                dropped.append(f"{rule_id}: unparseable uri")
                continue
            real = Path(os.path.realpath(abs_path))
            try:
                rel = real.relative_to(build_root).as_posix()
            except ValueError:
                dropped.append(f"{rule_id}: location outside the build copy ({art.get('uri')})")
                continue
            staged_file = staged_root / rel
            if not staged_file.is_file():
                dropped.append(f"{rule_id}: {rel} has no equivalent in the frozen snapshot")
                continue
            lines = read_lines(staged_file)
            start = int(region.get("startLine") or 0)
            end = int(region.get("endLine") or start)
            if start < 1 or end < start or end > len(lines):
                dropped.append(f"{rule_id}: invalid line range {start}-{end} in {rel}")
                continue
            cid = candidate_id(rule_id, rel, start, end)
            if cid in seen:
                continue
            excerpt = "\n".join(lines[start - 1 : end])
            seen[cid] = RoslynCandidate(
                candidate_id=cid,
                rule_id=rule_id,
                category=CATEGORY_BY_RULE[rule_id],
                file=rel,
                start_line=start,
                end_line=end,
                message=(res.get("message") or {}).get("text", ""),
                excerpt=excerpt[:2000],
            )
    candidates = sorted(seen.values(), key=lambda c: (c.file, c.start_line, c.rule_id))
    emitted = sorted({c.rule_id for c in candidates})
    missing = [r for r in selected if r not in emitted]
    return RoslynResult(
        status="ok",
        candidates=candidates,
        emitted_rule_ids=emitted,
        missing_rule_ids=missing,
        sarif_version=version,
        dropped_locations=dropped,
    )
